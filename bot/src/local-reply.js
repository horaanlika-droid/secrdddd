/* ============================================================
   Дибитишка · локальный ответ («память» вместо живого чата)
   ------------------------------------------------------------
   Нужен, когда живой чат недоступен: нет OPENAI_API_KEY, модель
   перегружена (429), таймаут, сеть — или модель сама прислала
   служебную фразу «меня сейчас слишком много спрашивают, попробуй
   позже». Вместо этой фразы человек получает обычный ответ
   Дибитишки, собранный из его же записей: якоря, антикризисный
   план, задания, освоенные навыки, серия дней и уровень.

   Это двойник локального чата в вебе (app/js/app.js → chatReply):
   меняешь тон — правь оба места.
   ============================================================ */

const clip = (s, n = 200) => {
  s = String(s || '').replace(/\s+/g, ' ').trim();
  return s.length > n ? s.slice(0, n - 1) + '…' : s;
};

const plural = (n, one, few, many) => {
  const a = Math.abs(n) % 100, b = a % 10;
  if (a > 10 && a < 20) return many;
  if (b > 1 && b < 5) return few;
  if (b === 1) return one;
  return many;
};

const pick = (arr) => arr[Math.floor(Math.random() * arr.length)];

/** Маленькие опоры «на сейчас» — те же, что в вебе. */
export const LOCAL_TIPS = [
  { text: 'Вдох на 4, выдох на 6. Три раза. Длинный выдох говорит телу: можно расслабиться.' },
  { text: 'Назови пять вещей, которые видишь, четыре — которые слышишь, три — которые чувствуешь кожей. Это заземление.' },
  { text: 'Одна маленькая задача на ближайшие пять минут. Не «разобраться со всем», а одно действие.' },
  { text: 'Холодная вода на запястья или лицо — быстрый способ вернуть тело в «здесь».' },
  { text: 'Если можно — приглуши свет и звук на пару минут. Меньше входящего — легче внутри.' }
];

/**
 * Ответ из локальной памяти.
 * @param {string} userText — что написал человек
 * @param {object} ctx — то же, что получает ai.js: name, level, streak, mastered[],
 *                       whoami, anchors, crisis, filled[], moodNow, moodCount, todayPractice
 */
export function localReply(userText, ctx = {}) {
  const t = String(userText || '').toLowerCase();
  const has = (...words) => words.some((w) => t.includes(w));
  const name = ctx.name ? `, ${ctx.name}` : '';
  const streak = Number(ctx.streak) || 0;
  const level = ctx.level != null ? ctx.level : null;
  const mastered = Array.isArray(ctx.mastered) ? ctx.mastered.filter(Boolean) : [];

  if (has('кто я', 'напомни', 'какой я', 'какая я', 'забыл', 'забыла', 'потерял', 'потеряла', 'кто ты')) {
    const parts = [];
    if (ctx.whoami) parts.push(`Ты писал(а) о себе: «${clip(ctx.whoami)}»`);
    if (ctx.anchors) parts.push(`Твои якоря: «${clip(ctx.anchors)}»`);
    if (mastered.length) parts.push(`Ты умеешь: ${mastered.slice(0, 4).map((m) => clip(m, 80)).join(' · ')}`);
    if (parts.length) {
      const path = streak || level
        ? `Ты — не этот момент${name}. Ты — тот, кто держался${streak ? ` ${streak} ${plural(streak, 'день', 'дня', 'дней')} подряд` : ''}${level ? ` и дошёл до уровня ${level}` : ''}.`
        : `Ты — не этот момент${name}.`;
      return `${path}\n\n${parts.join('\n')}\n\nЕсли сейчас тяжело — это волна, а ты глубже любой волны. 💧`;
    }
    return `Пока тут мало записей${name}, но это поправимо. Заполни в профиле задания «Кто я, когда мне хорошо» и «Мои якоря» — и я буду напоминать тебе о тебе твоими же словами.`;
  }

  if (has('тяжело', 'тревож', 'страш', 'паник', 'плохо', 'накры', 'тошн', 'больно', 'не могу', 'срыв', 'ужас')) {
    const crisis = ctx.crisis ? `\n\nТы сам(а) оставил(а) себе план на такой случай:\n«${clip(ctx.crisis)}»` : '';
    return `Слышу${name}. Давай по-маленькому, прямо сейчас:\n\n1. Выдох длиннее вдоха — три раза, медленно.\n2. Назови пять вещей, которые видишь. Ты здесь, а не там, где страшно.\n3. Одно действие на пять минут — и всё. Больше пока не надо.${crisis}\n\nЭто точка на пути, а не весь путь. Я рядом. 💧`;
  }

  if (has('совет', 'что делать', 'помог', 'подскаж', 'не знаю', 'как быть', 'как справ')) {
    return `Совет на сейчас: ${pick(LOCAL_TIPS).text}\n\nОдин вдох уже считается. Если хочешь глубже — загляни в «Навыки».`;
  }

  if (has('устал', 'устала', 'вымотан', 'сил нет', 'выгор', 'спать', 'отдох', 'утом')) {
    return `Усталость — это сигнал, а не слабость${name}. Тебе можно замедлиться.\n\nСегодня выбери одно маленькое «нет» и одно маленькое «можно отдохнуть». Меньше, чем кажется нужным, — уже достаточно.`;
  }

  if (has('спасибо', 'благодар')) {
    return 'Всегда рядом. Заходи, когда будет нужно — и когда будет хорошо, тоже. 💧';
  }

  if (has('привет', 'здравств', 'добрый', 'хай')) {
    return `Привет${name}! Я тут. Могу подсказать, как пережить трудный момент, напомнить, кто ты, или просто побыть рядом.`;
  }

  const practice = ctx.todayPractice ? `\n\nЕсли хочется опоры прямо сейчас — практика дня: «${clip(ctx.todayPractice, 90)}». Команда /today.` : '';
  return `Я слышу${name}. Я лучше всего умею: подсказать в трудный момент, напомнить, кто ты, и побыть рядом. Попробуй: «Мне тяжело», «Напомни, кто я» или «Дай совет».${practice}`;
}
